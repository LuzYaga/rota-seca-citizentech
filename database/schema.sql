-- 1. LIMPEZA PRÉVIA DAS TABELAS (DROP TABLE CASCADE)
DROP TABLE IF EXISTS AREA_CRITICA CASCADE;
DROP TABLE IF EXISTS REPORTE_ALAGAMENTO CASCADE;
DROP TABLE IF EXISTS ABRIGO_BAIRRO CASCADE;
DROP TABLE IF EXISTS ABRIGO CASCADE;
DROP TABLE IF EXISTS USUARIO CASCADE;
DROP TABLE IF EXISTS RUA CASCADE;
DROP TABLE IF EXISTS BAIRRO CASCADE;

-- 2. CRIAÇÃO DAS TABELAS

-- TABELA: BAIRRO
-- Armazena os bairros monitorados, sua macrorregião (ex.: Zona Sul) e o risco calculado.
CREATE TABLE BAIRRO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    zona VARCHAR(50) NOT NULL,
    nivel_risco VARCHAR(20) DEFAULT 'BAIXO' NOT NULL,
    CONSTRAINT chk_bairro_nivel_risco CHECK (nivel_risco IN ('BAIXO', 'MEDIO', 'ALTO'))
);

-- TABELA: RUA
-- Logradouros pertencentes aos bairros monitorados.
CREATE TABLE RUA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cep VARCHAR(20) NOT NULL,
    id_bairro BIGINT NOT NULL,
    CONSTRAINT fk_rua_bairro FOREIGN KEY (id_bairro) REFERENCES BAIRRO(id) ON DELETE CASCADE
);

-- TABELA: USUARIO
-- Cidadãos que interagem com o sistema (moradores, entregadores e pessoas com mobilidade reduzida).
CREATE TABLE USUARIO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    contato VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    info_adicional VARCHAR(200),
    CONSTRAINT chk_usuario_tipo CHECK (tipo IN ('MORADOR', 'ENTREGADOR', 'MOBILIDADE_REDUZIDA'))
);

-- TABELA: REPORTE_ALAGAMENTO
-- Registros enviados em tempo real pelos cidadãos sobre vias inundadas.
CREATE TABLE REPORTE_ALAGAMENTO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rua BIGINT NOT NULL,
    id_usuario BIGINT NOT NULL,
    nivel VARCHAR(10) NOT NULL,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT chk_reporte_nivel CHECK (nivel IN ('LEVE', 'MEDIO', 'GRAVE')),
    CONSTRAINT fk_reporte_rua FOREIGN KEY (id_rua) REFERENCES RUA(id) ON DELETE CASCADE,
    CONSTRAINT fk_reporte_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id) ON DELETE CASCADE
);

-- TABELA: ABRIGO
-- Locais públicos ou comunitários seguros destinados a acolhimento durante tempestades.
CREATE TABLE ABRIGO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    endereco VARCHAR(200) NOT NULL,
    capacidade INT NOT NULL,
    CONSTRAINT chk_abrigo_capacidade CHECK (capacidade > 0)
);

-- TABELA ASSOCIATIVA N:N: ABRIGO_BAIRRO
-- Relaciona quais abrigos atendem a quais bairros, incluindo atributo extra de distância operacional.
CREATE TABLE ABRIGO_BAIRRO (
    id_abrigo BIGINT NOT NULL,
    id_bairro BIGINT NOT NULL,
    distancia_km DECIMAL(5,2) NOT NULL,
    PRIMARY KEY (id_abrigo, id_bairro),
    CONSTRAINT chk_distancia CHECK (distancia_km >= 0),
    CONSTRAINT fk_abrigobairro_abrigo FOREIGN KEY (id_abrigo) REFERENCES ABRIGO(id) ON DELETE CASCADE,
    CONSTRAINT fk_abrigobairro_bairro FOREIGN KEY (id_bairro) REFERENCES BAIRRO(id) ON DELETE CASCADE
);

-- TABELA: AREA_CRITICA
-- Lugares históricos com grande recorrência ou potencial severo de alagamento gerados pelo sistema.
CREATE TABLE AREA_CRITICA (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bairro BIGINT NOT NULL,
    id_rua BIGINT NOT NULL,
    total_reportes INT NOT NULL,
    data_marcacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    nivel_alerta VARCHAR(20) NOT NULL,
    CONSTRAINT chk_area_critica_total CHECK (total_reportes >= 0),
    CONSTRAINT fk_areacritica_bairro FOREIGN KEY (id_bairro) REFERENCES BAIRRO(id) ON DELETE CASCADE,
    CONSTRAINT fk_areacritica_rua FOREIGN KEY (id_rua) REFERENCES RUA(id) ON DELETE CASCADE
);

