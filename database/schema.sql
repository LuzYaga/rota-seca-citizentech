-- 4. RELATÓRIOS ANALÍTICOS COM SQL (DIFERENCIAL: JOIN + AGREGAÇÃO)

-- Relatório 1: Ranking de Bairros com maior número de ocorrências e gravidade ponderada
-- Fórmula: LEVE = 1 pt, MEDIO = 2 pts, GRAVE = 3 pts
SELECT 
    b.nome AS bairro,
    b.zona,
    COUNT(r.id) AS total_ocorrencias,
    SUM(CASE WHEN r.nivel = 'LEVE' THEN 1 WHEN r.nivel = 'MEDIO' THEN 2 WHEN r.nivel = 'GRAVE' THEN 3 ELSE 0 END) AS pontuacao_risco,
    b.nivel_risco AS classificacao_bairro
FROM BAIRRO b
LEFT JOIN RUA ru ON b.id = ru.id_bairro
LEFT JOIN REPORTE_ALAGAMENTO r ON ru.id = r.id_rua
GROUP BY b.id, b.nome, b.zona, b.nivel_risco
ORDER BY pontuacao_risco DESC, total_ocorrencias DESC;

-- Relatório 2: Ruas com maior incidência de alagamentos graves (Pontos Críticos)
SELECT 
    ru.nome AS rua,
    b.nome AS bairro,
    COUNT(r.id) AS total_reportes_graves
FROM RUA ru
INNER JOIN BAIRRO b ON ru.id_bairro = b.id
INNER JOIN REPORTE_ALAGAMENTO r ON ru.id = r.id_rua
WHERE r.nivel = 'GRAVE'
GROUP BY ru.id, ru.nome, b.nome
ORDER BY total_reportes_graves DESC;

-- Relatório 3: Abrigos operacionais para bairros sob Risco Médio ou Alto com distâncias
SELECT 
    b.nome AS bairro_afetado,
    b.nivel_risco,
    a.nome AS abrigo_recomendado,
    a.endereco,
    a.capacidade,
    ab.distancia_km
FROM BAIRRO b
INNER JOIN ABRIGO_BAIRRO ab ON b.id = ab.id_bairro
INNER JOIN ABRIGO a ON ab.id_abrigo = a.id
WHERE b.nivel_risco IN ('MEDIO', 'ALTO')
ORDER BY b.nome, ab.distancia_km ASC;
